// Bundle the language explorer's globe (apps/mobile/explorer/globe.mjs) into
// apps/mobile/public/languages-globe.js: `npm run explorer:build`. The page is
// static and the web app allows no scripts from elsewhere, so d3-geo,
// topojson-client and the Reports map's shapes (world-atlas, 110m) go in the
// file. Each country carries its ISO 3166-1 alpha-2 code, which is what
// region_source holds. scripts/explorerGlobe.test.ts holds the committed
// file to this source.
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);

/** The shapes Natural Earth leaves without a numeric code, by name. */
const UNNUMBERED = { Kosovo: 'XK', Somaliland: 'SO', 'N. Cyprus': 'CY' };

export function worldWithCodes() {
  const world = structuredClone(require('world-atlas/countries-110m.json'));
  const iso = require('i18n-iso-countries');
  for (const g of world.objects.countries.geometries) {
    const a2 = (g.id && iso.numericToAlpha2(g.id)) || UNNUMBERED[g.properties.name];
    if (!a2) throw new Error(`no ISO 3166-1 code for ${g.properties.name}`);
    g.properties = { name: g.properties.name, a2 };
  }
  return world;
}

export const GLOBE_FILE = 'apps/mobile/public/languages-globe.js';

export async function bundleGlobe() {
  const out = await build({
    entryPoints: ['apps/mobile/explorer/globe.mjs'], outfile: GLOBE_FILE, write: false,
    bundle: true, minify: true, format: 'iife', target: 'es2020', platform: 'browser', legalComments: 'none',
    banner: { js: '// Generated by npm run explorer:build from apps/mobile/explorer/globe.mjs. d3-geo and topojson-client (ISC), world-atlas (ISC; Natural Earth, public domain).' },
    plugins: [{
      name: 'world',
      setup(b) {
        b.onResolve({ filter: /^explorer:world$/ }, () => ({ path: 'world', namespace: 'explorer' }));
        b.onLoad({ filter: /.*/, namespace: 'explorer' }, () => ({ contents: JSON.stringify(worldWithCodes()), loader: 'json' }));
      }
    }]
  });
  return out.outputFiles[0].text;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { writeFile } = await import('node:fs/promises');
  await writeFile(GLOBE_FILE, await bundleGlobe());
}
